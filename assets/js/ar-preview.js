  function norm(s) { return s.replace(/\s+/g, ' ').trim(); }
  // data-singular/-plural/-currency are read by ds.js recipes to BUILD text at
  // runtime, so they must be translated as well — otherwise the first render is
  // Arabic and the next slider drag rewrites it in English.
  var ATTRS = ['placeholder', 'aria-label', 'alt', 'title', 'data-singular', 'data-plural', 'data-currency'];
  // Scopes where a language NAME is the content, not UI copy. "عربي" maps to
  // "English" for the header toggle (in Arabic the toggle offers English), but
  // inside these lists it is the label of the Arabic edition of a site and must
  // stay Arabic — otherwise every row reads "English | English".
  var NO_TRANSLATE = '.ish-site-langs';
  function translate(scope) {
    if (!scope) return;
    var walker = document.createTreeWalker(scope, NodeFilter.SHOW_TEXT, null);
    var n;
    while ((n = walker.nextNode())) {
      var p = n.parentElement;
      if (p && /^(SCRIPT|STYLE)$/.test(p.tagName)) continue;
      if (p && p.closest && p.closest(NO_TRANSLATE)) continue;
      var key = norm(n.nodeValue || '');
      if (key && Object.prototype.hasOwnProperty.call(M, key)) {
        // keep the node's original leading/trailing whitespace — inline
        // word-spans (reveal animations) depend on it for word separation
        var ws = n.nodeValue.match(/^(\s*)[\s\S]*?(\s*)$/);
        n.nodeValue = ws[1] + M[key] + ws[2];
      }
    }
    var els = scope.querySelectorAll('[' + ATTRS.join('],[') + ']');
    for (var i = 0; i < els.length; i++) {
      for (var j = 0; j < ATTRS.length; j++) {
        var v = els[i].getAttribute(ATTRS[j]);
        if (!v) continue;
        var key2 = norm(v);
        if (Object.prototype.hasOwnProperty.call(M, key2)) els[i].setAttribute(ATTRS[j], M[key2]);
      }
    }
  }
  window.ARP = { translate: translate, dict: M };
