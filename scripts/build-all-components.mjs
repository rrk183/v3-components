#!/usr/bin/env node
// all-components.html generator — single source of truth for the cross-browser
// review page. Order = gallery catalog (library.js slugs) + any uncataloged
// blocks; site-header first, footers last. The page body sits between
// BLOCKS:BEGIN/END markers so the verify gate can assert freshness.
//
//   node scripts/build-all-components.mjs --write   regenerate the page
//   node scripts/build-all-components.mjs --check   exit 1 if page is stale
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(path.join(ROOT, p), "utf8");

export function blockOrder() {
  const cat = read("assets/js/library.js");
  const slugs = [];
  for (const m of cat.matchAll(/slug:\s*'([a-z0-9-]+)'/g))
    if (!slugs.includes(m[1])) slugs.push(m[1]);
  const files = readdirSync(path.join(ROOT, "blocks"))
    .filter((f) => f.endsWith(".html"))
    .map((f) => f.slice(0, -5))
    .sort();
  const order = [
    ...slugs.filter((s) => files.includes(s)),
    ...files.filter((b) => !slugs.includes(b)),
  ];
  for (const f of ["footer-option1", "footer-option2"]) {
    const i = order.indexOf(f);
    if (i >= 0) { order.splice(i, 1); order.push(f); }
  }
  const h = order.indexOf("site-header");
  if (h > 0) { order.splice(h, 1); order.unshift("site-header"); }
  // The header v2 comparison variants are position:fixed like site-header —
  // stacking three fixed headers here would overlay each other at the top of
  // the review page. They are compared side-by-side in the gallery instead.
  for (const f of ["site-header-v2", "site-header-v2-scroll", "site-header-v4"]) {
    const i = order.indexOf(f);
    if (i >= 0) order.splice(i, 1);
  }
  return order;
}

export function buildBody() {
  return blockOrder()
    .map((s) => read(`blocks/${s}.html`).trim())
    .join("\n\n");
}

export function currentVersion() {
  const m = read("index.html").match(/ds\.css\?v=(\w+)/);
  if (!m) throw new Error("cannot read ?v= from index.html");
  return m[1];
}

export function buildPage() {
  const v = currentVersion();
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <script src="assets/js/gate-config.js"></script>
  <script src="assets/js/gate.js"></script>
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>All Components — browser pass | Emirates NBD DS</title>
  <meta name="description" content="Internal review page: every design-system block stacked as one seamless page for cross-browser and breakpoint passes." />
  <meta name="robots" content="noindex" />
  <link rel="stylesheet" href="assets/css/fonts.css" />
  <link rel="stylesheet" href="assets/css/ds.css?v=${v}" />
  <link rel="stylesheet" href="assets/css/themes.css?v=${v}" />
  <script src="assets/js/tailwind.cdn.js"></script>
  <script src="assets/js/ds-tailwind-config.js?v=${v}"></script>
  <script defer src="assets/js/ds.js?v=${v}"></script>
  <style>body{margin:0}</style>
</head>
<body>
<!-- Generated by scripts/build-all-components.mjs — do not hand-edit.
     Every block in blocks/, stacked seamlessly (no separators) as one page,
     for cross-browser visual passes. -->
<!-- BLOCKS:BEGIN -->
${buildBody()}
<!-- BLOCKS:END -->
</body>
</html>
`;
}

const mode = process.argv[2];
if (mode === "--write") {
  writeFileSync(path.join(ROOT, "all-components.html"), buildPage());
  console.log(`all-components.html regenerated (${blockOrder().length} blocks)`);
} else if (mode === "--check") {
  let current = "";
  try { current = read("all-components.html"); } catch {}
  if (current === buildPage()) {
    console.log("all-components.html is fresh");
  } else {
    console.error("all-components.html is STALE — run: node scripts/build-all-components.mjs --write");
    process.exit(1);
  }
}
